-- ------------------------------------------------------------
-- STEP 2: CREATE HISTORICAL TELEMETRY LOGS TABLE
-- Stores touch events, check-ins, and round completions for any band/station
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.telemetry_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    station_id TEXT NOT NULL,
    target_device TEXT NOT NULL,
    event TEXT NOT NULL,
    lap_duration_sec NUMERIC(10, 2) DEFAULT 0.00,
    signal_rssi INT NOT NULL,
    est_distance_cm NUMERIC(10, 2) DEFAULT 0.00,
    uptime_ms BIGINT DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_telemetry_station_device 
ON public.telemetry_logs (station_id, target_device, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_telemetry_device_time
ON public.telemetry_logs (target_device, created_at DESC);

-- ------------------------------------------------------------
-- STEP 3: CREATE WORKERS TABLE (Live Real-Time Dashboard State)
-- Tracks all operators, wristbands, live positions, and motion states
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.workers (
    worker_id TEXT PRIMARY KEY,
    device_id TEXT NOT NULL,
    current_zone TEXT DEFAULT 'Side A',
    last_beacon_id TEXT DEFAULT 'M1-A1',
    beacon_rssi INT DEFAULT -70,
    current_machine TEXT DEFAULT 'M1',
    lap_count INT DEFAULT 0,
    lap_duration_sec NUMERIC(10, 2) DEFAULT 0.00,
    directional_heading TEXT DEFAULT 'Stationary',
    motion_state TEXT DEFAULT 'stationary',
    idle_duration_sec INT DEFAULT 0,
    walking_speed_ms NUMERIC(4, 2) DEFAULT 0.00,
    shift_status TEXT DEFAULT 'active',
    incident_type TEXT DEFAULT 'none',
    assistance_request_flag BOOLEAN DEFAULT FALSE,
    wristband_battery_pct INT DEFAULT 100,
    beacon_battery_pct INT DEFAULT 100,
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Ensure numeric precision for decimal lap durations and universal timestamp compatibility
ALTER TABLE IF EXISTS public.workers 
